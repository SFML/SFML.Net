using System;
using System.Runtime.InteropServices;
using System.Security;
using SFML.System;

namespace SFML.Audio;

/// <summary>
/// Queries state over sound stuff
/// </summary>
public static class PlaybackDevice
{
    /// <summary>
    /// Enumeration of the playback device notifications.
    /// </summary>
    public enum Notification
    {
        /// <summary> Playback device has been started.  </summary>
        Started,

        /// <summary> Playback device has been stopped.  </summary>
        Stopped,

        /// <summary> Playback device has been rerouted (Generated on platforms that support automatic stream routing).  </summary>
        Rerouted,

        /// <summary> Playback device interruption has begun (Generated on Apple mobile platforms).  </summary>
        InterruptionBegan,

        /// <summary> Playback device interruption has ended (Generated on Apple mobile platforms).  </summary>
        InterruptionEnded,

        /// <summary> Playback device has been unlocked (Generated by Emscripten/WebAudio).  </summary>
        Unlocked
    }

    /// <summary>
    /// Callable that is called to notify of changes to the playback device state.
    /// </summary>
    public delegate void NotificationCallback(Notification notification, object userData);

    /// <summary>
    /// Get a list of the names of all available audio playback devices
    /// </summary>
    /// <returns>An array of strings containing the device names or empty if no devices are available</returns>
    public static string[] GetAvailableDevices()
    {
        unsafe
        {
            ulong length = 0;
            var buffer = sfPlaybackDevice_getAvailableDevices(ref length);
            var devices = new string[length];
            for (ulong i = 0; i < length; i++)
            {
                devices[i] = Marshal.PtrToStringAnsi(*buffer);
                buffer++;
            }
            return devices;
        }
    }

    /// <summary>
    /// Get the name of the default audio playback device
    /// </summary>
    /// <returns>The name of the default audio playback device or NULL if there is none</returns>
    public static string GetDefaultDevice()
    {
        var device = sfPlaybackDevice_getDefaultDevice();
        return device == IntPtr.Zero ? null : Marshal.PtrToStringAnsi(device);
    }

    /// <summary>
    /// Set the audio playback device
    /// </summary>
    /// <param name="device"></param>
    /// <returns>True, if it was able to set the requested device</returns>
    public static bool SetDevice(string device) => sfPlaybackDevice_setDevice(device);

    /// <summary>
    /// Set the audio playback device to the default
    /// </summary>
    /// <returns>True, if it was able to set the audio playback device to the default device</returns>
    public static bool SetDeviceToDefault() => sfPlaybackDevice_setDeviceToDefault();

    /// <summary>
    /// Set the audio playback device to the null device
    /// </summary>
    /// <returns></returns>
    public static bool SetDeviceToNull() => sfPlaybackDevice_setDeviceToNull();

    /// <summary>
    /// Get the name of the current audio playback device
    /// </summary>
    /// <returns></returns>
    public static string GetDevice()
    {
        var device = sfPlaybackDevice_getDevice();
        return device == IntPtr.Zero ? null : Marshal.PtrToStringAnsi(device);
    }


    #region Imports

    [DllImport(CSFML.Audio, CallingConvention = CallingConvention.Cdecl), SuppressUnmanagedCodeSecurity]
    private static extern unsafe IntPtr* sfPlaybackDevice_getAvailableDevices(ref ulong count);

    [DllImport(CSFML.Audio, CallingConvention = CallingConvention.Cdecl), SuppressUnmanagedCodeSecurity]
    private static extern IntPtr sfPlaybackDevice_getDefaultDevice();

    [DllImport(CSFML.Audio, CallingConvention = CallingConvention.Cdecl), SuppressUnmanagedCodeSecurity]
    private static extern bool sfPlaybackDevice_setDevice(string device);

    [DllImport(CSFML.Audio, CallingConvention = CallingConvention.Cdecl), SuppressUnmanagedCodeSecurity]
    private static extern bool sfPlaybackDevice_setDeviceToDefault();

    [DllImport(CSFML.Audio, CallingConvention = CallingConvention.Cdecl), SuppressUnmanagedCodeSecurity]
    private static extern bool sfPlaybackDevice_setDeviceToNull();

    [DllImport(CSFML.Audio, CallingConvention = CallingConvention.Cdecl), SuppressUnmanagedCodeSecurity]
    private static extern IntPtr sfPlaybackDevice_getDevice();

    #endregion
}